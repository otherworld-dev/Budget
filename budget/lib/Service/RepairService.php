/**
 * Diagnoses and repairs data integrity issues.
 */
class RepairService {
	/**
	 * Every repair category id, in the order diagnose() reports them.
	 * SetupController validates the request against this rather than keeping its
	 * own literal copy — a category added here is immediately accepted.
	 */
	public const CATEGORIES = [
		'duplicateTransactions',
		'stuckBills',
		'paidOneTimeBills',
		'stuckIncome',
		'futureClearedTransactions',
		'transferCreditCategories',
		'liabilitySignFlipped',
		'splitParentCategories',
		'balanceDrift',
	];

	/**
	 * How many days before its due date a payment can be made and still be
	 * taken as that occurrence's payment, when matching a bill's payments to
	 * its occurrences. Lateness has no limit: overdue occurrences are often
	 * caught up together, weeks later.
	 */
	private const EARLY_PAYMENT_DAYS = [
		'daily' => 1,
		'weekly' => 3,
		'biweekly' => 7,
		'semi-monthly' => 7,
		'monthly' => 15,
		'quarterly' => 45,
		'semi-annually' => 90,
		'yearly' => 180,
		'one-time' => 30,
	];

	/**
	 * How far a payment may sit from a one-time bill's date and still be its
	 * payment, once the bill is one-time and its old schedule is gone: a
	 * weekend or a bank holiday either side, as editing the bill judges it
	 * (#399). A week off is a payment of its own.
	 */
	private const ONE_TIME_PAYMENT_DAYS = 3;

	/** Furthest apart two payments of a deleted bill are taken for one paid twice */
	private const DELETED_BILL_DOUBLE_DAYS = 3;

	/**
	 * Taking a bill's pending row up as its payment books the next
	 * occurrence's pending row in the same request: within this many
	 * seconds of the row's last change.
	 */
	private const TAKEN_UP_SECONDS = 2;

	private TransactionMapper $transactionMapper;
	private BillMapper $billMapper;
	private AccountMapper $accountMapper;
	private FrequencyCalculator $frequencyCalculator;
	private AccountService $accountService;
	private TransactionService $transactionService;
	private AccountBalanceCalculator $balanceCalculator;
	private ?UserClock $userClock;
	private ?LegacyIncomeRows $legacyIncomeRows;

	public function __construct(
		TransactionMapper $transactionMapper,
		BillMapper $billMapper,
		AccountMapper $accountMapper,
		FrequencyCalculator $frequencyCalculator,
		AccountService $accountService,
		TransactionService $transactionService,
		?UserClock $userClock = null,
		?LegacyIncomeRows $legacyIncomeRows = null,
	) {
		$this->transactionMapper = $transactionMapper;
		$this->billMapper = $billMapper;
		$this->accountMapper = $accountMapper;
		$this->frequencyCalculator = $frequencyCalculator;
		$this->accountService = $accountService;
		$this->transactionService = $transactionService;
		$this->userClock = $userClock;
		$this->legacyIncomeRows = $legacyIncomeRows;
		$this->balanceCalculator = new AccountBalanceCalculator($accountMapper, $transactionMapper);
	}

	/**
	 * The user's own today: what counts as a future date is a question about
	 * their calendar, not the server's (see UserClock).
	 */
	private function today(string $userId): string {
		return $this->userClock !== null ? $this->userClock->today($userId) : date('Y-m-d');
	}

	/**
	 * The index of the first row dated on or before $date, in rows sorted
	 * newest first (count($rows) when there is none).
	 *
	 * @param list<array<string, mixed>> $rows
	 */
	private static function firstRowOnOrBefore(array $rows, string $date): int {
		$low = 0;
		$high = count($rows);
		while ($low < $high) {
			$mid = intdiv($low + $high, 2);
			if ((string)$rows[$mid]['date'] > $date) {
				$low = $mid + 1;
			} else {
				$high = $mid;
			}
		}
		return $low;
	}

	private static function addDays(string $date, int $days): string {
		return (new \DateTimeImmutable($date))->modify(($days >= 0 ? '+' : '') . $days . ' days')->format('Y-m-d');
	}

	/**
	 * Diagnose data integrity issues without making any changes.
	 *
	 * @return array Categorized findings
	 */
	public function diagnose(string $userId): array {
		return [
			'duplicateTransactions' => $this->findDuplicateAutoGenerated($userId),
			'stuckBills' => $this->findStuckBills($userId),
			'paidOneTimeBills' => $this->findPaidOneTimeBillsStillActive($userId),
			'stuckIncome' => $this->findStuckIncome($userId),
			'futureClearedTransactions' => $this->findFutureClearedTransactions($userId),
			// Transfer credits now correctly preserve categories (since v2.26.3)
			'transferCreditCategories' => [],
			'liabilitySignFlipped' => $this->findLiabilitySignFlipped($userId),
			'splitParentCategories' => $this->findCategorisedSplitParents($userId),
			'balanceDrift' => $this->findBalanceDrift($userId),
		];
	}

	/**
	 * Repair specific categories of issues.
	 *
	 * @param string[] $categories Which categories to fix: 'duplicateTransactions', 'stuckBills', 'balanceDrift'
	 * @param array $options 'accountIds' for liabilitySignFlipped; 'transactionIds' for
	 *                       duplicateTransactions: the rows the user ticked. Without it,
	 *                       only the duplicates the scan is sure of are removed.
	 * @return array Results per category
	 */
	public function repair(string $userId, array $categories, array $options = []): array {
		$results = [];

		if (in_array('duplicateTransactions', $categories)) {
			$results['duplicateTransactions'] = $this->repairDuplicateAutoGenerated(
				$userId,
				isset($options['transactionIds']) && is_array($options['transactionIds'])
					? array_map('intval', $options['transactionIds'])
					: null
			);
		}

		if (in_array('stuckBills', $categories)) {
			$results['stuckBills'] = $this->repairStuckBills($userId);
		}

		if (in_array('paidOneTimeBills', $categories)) {
			$results['paidOneTimeBills'] = $this->repairPaidOneTimeBills($userId);
		}

		if (in_array('stuckIncome', $categories)) {
			$results['stuckIncome'] = $this->repairStuckIncome($userId);
		}

		if (in_array('futureClearedTransactions', $categories)) {
			$results['futureClearedTransactions'] = $this->repairFutureClearedTransactions($userId);
		}

		// transferCreditCategories repair removed — credits now correctly keep categories

		if (in_array('liabilitySignFlipped', $categories)) {
			$results['liabilitySignFlipped'] = $this->repairLiabilitySignFlipped(
				$userId,
				isset($options['accountIds']) && is_array($options['accountIds'])
					? array_map('intval', $options['accountIds'])
					: null
			);
		}

		if (in_array('splitParentCategories', $categories)) {
			$results['splitParentCategories'] = $this->repairCategorisedSplitParents($userId);
		}

		// Balance recalculation should always run last (after tx cleanup)
		if (in_array('balanceDrift', $categories)) {
			$results['balanceDrift'] = $this->accountService->recalculateAllBalances($userId);
		}

		return $results;
	}

	/**
	 * Find bill payments recorded twice.
	 *
	 * Two kinds, each reported as a pair: the row to remove and the row it
	 * duplicates.
	 *
	 *  - A payment the app generated (Mark Paid, auto-pay, Record
	 *    transaction) that the bank's own row records as well.
	 *  - Two of one bill's payments that settle the same occurrence.
	 *
	 * Only a pair the rows themselves prove is 'selected': pre-ticked in the
	 * preview, and removed by a repair that names no rows. That is a
	 * generated payment next to an imported row of the same amount, supplier
	 * and direction that belongs to no bill. Everything else is a likely
	 * duplicate, not a certain one, so it is listed for the user to check and
	 * removed only when they tick it. A reconciled row is never offered.
	 *
	 * Rows of different bills are never paired, and neither are payments of
	 * different occurrences of one bill. A bill's name and amount, the month
	 * a payment fell in and the second a row was written say nothing about
	 * which occurrence it paid, and pairing on them deleted real payments.
	 * A deleted bill's payments, whose schedule went with it, are paired
	 * only when one booking looks repeated: same name, amount and account,
	 * a few days apart.
	 */
	private function findDuplicateAutoGenerated(string $userId): array {
		$today = $this->today($userId);
		$accounts = $this->accountMapper->findAll($userId);
		$duplicates = [];
		$usedOriginals = [];
		$generated = [];

		foreach ($accounts as $account) {
			// Future-dated rows are the futureClearedTransactions category's
			$autoGen = array_values(array_filter(
				$this->transactionMapper->findAutoGeneratedBillTransactions($account->getId()),
				fn (Transaction $tx) => $tx->getDate() <= $today
			));
			$this->findAutoGenDuplicatesOfManualEntries($account, $autoGen, $duplicates, $usedOriginals);
			$generated = array_merge($generated, $autoGen);
		}

		$bills = $this->billMapper->findAll($userId);
		$this->findSameOccurrencePayments($bills, $accounts, $today, $duplicates);
		$this->findDeletedBillPayments($bills, $accounts, $generated, $duplicates);

		return $duplicates;
	}

	/**
	 * Generated bill payments that an imported or hand-entered row in the same
	 * account records as well.
	 *
	 * The other row has to go the same way (a refund is not a payment),
	 * belong to no bill or to this one (another bill's payment from the same
	 * supplier is that bill's), name the bill as a whole word, and be within
	 * three days and 25% of the amount. It is pre-selected only when it is
	 * the bank's own imported row, for exactly the amount and on no bill.
	 *
	 * @param Transaction[] $autoGen
	 * @param array<int, bool> $usedOriginals rows already standing as the original of a pair
	 */
	private function findAutoGenDuplicatesOfManualEntries(Account $account, array $autoGen, array &$duplicates, array &$usedOriginals): void {
		$accountId = $account->getId();
		// The account's rows near each payment come from one read per year
		// of payments, not one query per payment (T6-9: 859 queries for a
		// long history). A year's rows hold every payment's three-day
		// window; they come newest first (date, then id), so a window is
		// found by binary search and lists its rows in the order the
		// per-payment read did. Only rows inside a window become entities,
		// each once; only the latest year is kept in memory.
		$year = null;
		$yearRows = [];
		$entities = [];

		foreach ($autoGen as $tx) {
			// Checked against a statement: it stays, whatever else is there
			if ($tx->getReconciled()) {
				continue;
			}
			$names = $this->billNamesOf($tx);
			if ($names === []) {
				continue;
			}

			$from = self::addDays($tx->getDate(), -3);
			$to = self::addDays($tx->getDate(), 3);
			if ($year !== substr($tx->getDate(), 0, 4)) {
				$year = substr($tx->getDate(), 0, 4);
				$yearRows = $this->transactionMapper->findRowsByDateRange(
					$accountId,
					self::addDays($year . '-01-01', -3),
					self::addDays($year . '-12-31', 3)
				);
				$entities = [];
			}
			$candidates = [];
			$rowCount = count($yearRows);
			for ($i = self::firstRowOnOrBefore($yearRows, $to); $i < $rowCount && (string)$yearRows[$i]['date'] >= $from; $i++) {
				$candidates[] = $entities[$i] ??= Transaction::fromRow($yearRows[$i]);
			}
			$amount = (float)$tx->getAmount();
			$match = null;
			$matchIsCertain = false;

			foreach ($candidates as $candidate) {
				if ($candidate->getId() === $tx->getId() || isset($usedOriginals[$candidate->getId()])) {
					continue;
				}
				if (str_starts_with($candidate->getNotes() ?? '', 'Auto-generated')
					|| $candidate->getType() !== $tx->getType()
					|| ($candidate->getStatus() ?? 'cleared') === 'scheduled'
					|| ($candidate->getBillId() !== null && $candidate->getBillId() !== $tx->getBillId())
					|| !$this->namesBill($candidate, $names)) {
					continue;
				}
				$candidateAmount = (float)$candidate->getAmount();
				$exact = abs($amount - $candidateAmount) < 0.005;
				if (!$exact && !($amount > 0 && abs($amount - $candidateAmount) / $amount <= 0.25)) {
					continue;
				}

				$certain = $exact && $candidate->getBillId() === null
					&& $candidate->getImportId() !== null && $candidate->getImportId() !== '';
				$closer = $match !== null
					&& self::daysApart($candidate->getDate(), $tx->getDate()) < self::daysApart($match->getDate(), $tx->getDate());
				if ($match === null || ($certain && !$matchIsCertain) || ($certain === $matchIsCertain && $closer)) {
					$match = $candidate;
					$matchIsCertain = $certain;
				}
			}

			if ($match === null) {
				continue;
			}
			$usedOriginals[$match->getId()] = true;
			$duplicates[] = $this->duplicateFinding($tx, $match, $account->getName(), 'auto_gen_duplicates_manual', $matchIsCertain);
		}
	}

	/**
	 * Pairs of one bill's payments that settle the same occurrence.
	 *
	 * A payment settles one occurrence, in order, and only the occurrences
	 * before a bill's next due date are settled. So the bill's payments are
	 * matched, oldest first, to its settled occurrences, each taking the
	 * earliest one still free that it could be paying: any from the first
	 * payment's own occurrence on, as long as the payment isn't made more
	 * than a little ahead of it (EARLY_PAYMENT_DAYS). Late payments, overdue
	 * occurrences caught up on one day and payments made a few days early
	 * all find an occurrence of their own. A payment left without one paid
	 * an occurrence that was already paid, and is paired with the payment
	 * holding it.
	 *
	 * A skipped occurrence leaves room, which can hide a pair but never makes
	 * one up. A bill whose payments mostly don't fit its schedule had the
	 * schedule changed under them, so it is left out rather than reported
	 * payment by payment. Nothing here is certain, so nothing is pre-selected.
	 *
	 * A transfer's payment is its withdrawal, and removing it takes the
	 * deposit with it. Two payments of different amounts are two payments,
	 * unless one is a pending row the old scheduled job booked
	 * (clearedByTheOldJob()): paying the bill then booked the occurrence again,
	 * at whatever the bill's amount was by then.
	 *
	 * @param Bill[] $bills
	 * @param Account[] $accounts
	 */
	private function findSameOccurrencePayments(array $bills, array $accounts, string $today, array &$duplicates): void {
		$accountNames = [];
		foreach ($accounts as $account) {
			$accountNames[$account->getId()] = $account->getName();
		}
		$billsById = [];
		foreach ($bills as $bill) {
			$billsById[$bill->getId()] = $bill;
		}
		if ($billsById === [] || $accountNames === []) {
			return;
		}

		$rowsByBill = [];
		// When each bill's rows were written, wherever they sit
		$writtenAt = [];
		foreach ($this->transactionMapper->findRecordedByBillIds(array_keys($billsById)) as $tx) {
			$writtenAt[$tx->getBillId()][self::second($tx->getCreatedAt())] = true;
			// Debits only: a transfer's deposit is the other half of its
			// withdrawal, not a payment of its own
			if (isset($accountNames[$tx->getAccountId()]) && $tx->getDate() <= $today && $tx->getType() === 'debit') {
				$rowsByBill[$tx->getBillId()][] = $tx;
			}
		}

		$flagged = self::flaggedRows($duplicates);

		foreach ($rowsByBill as $billId => $rows) {
			if (count($rows) < 2) {
				continue;
			}
			$bill = $billsById[$billId];
			$pairs = $this->paymentsSharingAnOccurrence($bill, $rows);
			if (count($pairs) * 2 > count($rows)) {
				continue;
			}
			$written = $this->paymentRowIds($bill);
			$named = $this->snapshotRowIds($bill);

			foreach ($pairs as [$surplus, $holder, $occurrence]) {
				if (isset($flagged[$surplus->getId()]) || isset($flagged[$holder->getId()])
					|| $surplus->getAccountId() !== $holder->getAccountId()) {
					continue;
				}
				$byOldJob = array_values(array_filter([$surplus, $holder],
					fn (Transaction $tx) => self::clearedByTheOldJob($tx, $named, $writtenAt[$billId] ?? [])));
				if ($byOldJob === [] && abs((float)$surplus->getAmount() - (float)$holder->getAmount()) >= 0.005) {
					continue;
				}
				// A transfer goes with its deposit, so a deposit checked
				// against a statement keeps its withdrawal too
				$removable = array_values(array_filter([$surplus, $holder], fn (Transaction $tx) => self::removable($tx)
					&& !(($bill->getIsTransfer() ?? false) && $this->depositReconciled($tx))));
				$pick = self::rowToOffer($bill, $surplus, $removable, $byOldJob, $written);
				if ($pick === null) {
					continue;
				}
				$original = $pick === $surplus ? $holder : $surplus;
				$flagged[$pick->getId()] = true;
				$flagged[$original->getId()] = true;
				$finding = $this->duplicateFinding($pick, $original, $accountNames[$pick->getAccountId()], 'same_occurrence', false)
					+ ['occurrence' => $occurrence, 'billName' => $bill->getName(), 'transfer' => (bool)($bill->getIsTransfer() ?? false)];
				// The older payment is the one-time bill's own: removing the
				// newer leaves the bill paid by it
				if ($pick === $surplus && $bill->getFrequency() === 'one-time' && in_array($pick->getId(), $written, true)) {
					$finding['paidDateAfterRepair'] = $holder->getDate();
				}
				$duplicates[] = $finding;
			}
		}
	}

	/**
	 * Which row of a pair to offer for removal, if any.
	 *
	 *  - The old job's pending row: the one that should never have been
	 *    booked.
	 *  - For a one-time bill paid again, the newer payment. The last
	 *    snapshot names it, but the older one paid the bill's date, and
	 *    Mark Unpaid would re-open a bill already paid. Offering the older
	 *    one deleted the payment dated right.
	 *  - Otherwise a row the last payment didn't write, as Mark Unpaid takes
	 *    back the rows it wrote, else the later one.
	 *
	 * @param Transaction[] $removable the rows of the pair that may go, the later first
	 * @param Transaction[] $byOldJob the rows of the pair the old job booked
	 * @param int[] $written the rows the last payment wrote
	 */
	private static function rowToOffer(Bill $bill, Transaction $surplus, array $removable, array $byOldJob, array $written): ?Transaction {
		foreach ($byOldJob as $row) {
			if (in_array($row, $removable, true)) {
				return $row;
			}
		}
		if ($bill->getFrequency() === 'one-time' && in_array($surplus, $removable, true) && in_array($surplus->getId(), $written, true)) {
			return $surplus;
		}
		foreach ($removable as $row) {
			if (!in_array($row->getId(), $written, true)) {
				return $row;
			}
		}
		return $removable[0] ?? null;
	}

	/**
	 * Pairs of a deleted bill's payments that look like one payment booked
	 * twice.
	 *
	 * The bill's schedule went with it, so its payments can't be matched to
	 * occurrences; only the notes it wrote on them still name it. Two of them
	 * in one account under the same name, for the same amount and at most
	 * DELETED_BILL_DOUBLE_DAYS apart, are what the old job's pending row and
	 * the payment Mark Paid booked after it look like. They are listed for the
	 * user to check, offering the old job's row, else the later one.
	 *
	 * A row naming a bill of someone else's, booked into an account they
	 * share with the user, is not a deleted bill's. A deleted transfer's
	 * sides aren't paired: once its bill is gone, removing one side would
	 * leave the other behind.
	 *
	 * @param Bill[] $bills the user's bills
	 * @param Account[] $accounts
	 * @param Transaction[] $generated the bill payments the app generated in the user's accounts
	 */
	private function findDeletedBillPayments(array $bills, array $accounts, array $generated, array &$duplicates): void {
		$accountNames = [];
		foreach ($accounts as $account) {
			$accountNames[$account->getId()] = $account->getName();
		}
		$live = [];
		foreach ($bills as $bill) {
			$live[$bill->getId()] = true;
		}
		$elsewhere = array_values(array_unique(array_filter(
			array_map(fn (Transaction $tx) => $tx->getBillId(), $generated),
			fn (?int $id) => $id !== null && !isset($live[$id])
		)));
		if ($elsewhere !== []) {
			foreach ($this->billMapper->findByIds($elsewhere) as $bill) {
				$live[$bill->getId()] = true;
			}
		}

		$byName = [];
		foreach ($generated as $tx) {
			if (($tx->getBillId() !== null && isset($live[$tx->getBillId()]))
				|| !preg_match('/^Auto-generated from bill: (.+)$/', $tx->getNotes() ?? '', $m)) {
				continue;
			}
			$byName[$tx->getAccountId() . "\n" . trim($m[1])][] = $tx;
		}

		$flagged = self::flaggedRows($duplicates);
		foreach ($byName as $key => $rows) {
			usort($rows, fn (Transaction $a, Transaction $b) => [$a->getDate(), $a->getId()] <=> [$b->getDate(), $b->getId()]);
			[, $billName] = explode("\n", $key, 2);
			$writtenAt = [];
			foreach ($rows as $tx) {
				$writtenAt[self::second($tx->getCreatedAt())] = true;
			}
			$count = count($rows);
			for ($i = 0; $i < $count; $i++) {
				for ($j = $i + 1; $j < $count && self::daysApart($rows[$i]->getDate(), $rows[$j]->getDate()) <= self::DELETED_BILL_DOUBLE_DAYS; $j++) {
					[$earlier, $later] = [$rows[$i], $rows[$j]];
					if (isset($flagged[$earlier->getId()]) || isset($flagged[$later->getId()])
						|| $earlier->getType() !== $later->getType()
						|| abs((float)$earlier->getAmount() - (float)$later->getAmount()) >= 0.005) {
						continue;
					}
					$removable = array_values(array_filter([$later, $earlier], fn (Transaction $tx) => self::removable($tx)));
					$byOldJob = array_values(array_filter($removable, fn (Transaction $tx) => self::clearedByTheOldJob($tx, [], $writtenAt)));
					$pick = $byOldJob[0] ?? $removable[0] ?? null;
					if ($pick === null) {
						continue;
					}
					$original = $pick === $later ? $earlier : $later;
					$flagged[$earlier->getId()] = true;
					$flagged[$later->getId()] = true;
					$duplicates[] = $this->duplicateFinding($pick, $original, $accountNames[$pick->getAccountId()] ?? '', 'deleted_bill', false)
						+ ['billName' => $billName];
					continue 2;
				}
			}
		}
	}

	/**
	 * Whether a bill's row is a pending row the scheduled job booked before
	 * 3.0. The job cleared a bill's pending row on its date while the bill
	 * stayed due, so paying the bill then booked the same occurrence again.
	 * Such a row was written before its date (by the payment before it), last
	 * changed on its date, and no payment of the bill names it.
	 *
	 * A pending row Mark Paid or auto-pay took up as the payment, on its due
	 * date, looks the same. But taking it up booked the next occurrence's
	 * pending row in the same moment, which the job never did, so a row of
	 * the bill written just after it was last changed rules it out.
	 *
	 * @param int[] $named the rows the bill's undo snapshot names
	 * @param array<string, true> $writtenAt the seconds the bill's rows were written in
	 */
	private static function clearedByTheOldJob(Transaction $tx, array $named, array $writtenAt): bool {
		$date = substr((string)$tx->getDate(), 0, 10);
		$written = substr((string)$tx->getCreatedAt(), 0, 10);
		$changed = self::second($tx->getUpdatedAt());
		return self::bookedForABill($tx)
			&& ($tx->getStatus() ?? 'cleared') === 'cleared'
			&& $written !== '' && $written < $date
			&& substr($changed, 0, 10) === $date
			&& !in_array($tx->getId(), $named, true)
			&& !self::writtenJustAfter($changed, $writtenAt);
	}

	/**
	 * Whether one of the rows was written within TAKEN_UP_SECONDS after
	 * $moment.
	 *
	 * @param array<string, true> $writtenAt the seconds the rows were written in
	 */
	private static function writtenJustAfter(string $moment, array $writtenAt): bool {
		if (!preg_match('/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/', $moment)) {
			return false;
		}
		$at = new \DateTimeImmutable($moment, new \DateTimeZone('UTC'));
		for ($second = 0; $second <= self::TAKEN_UP_SECONDS; $second++) {
			if (isset($writtenAt[$at->modify("+{$second} seconds")->format('Y-m-d H:i:s')])) {
				return true;
			}
		}
		return false;
	}

	/** A timestamp to the second, as the database keeps it */
	private static function second(?string $timestamp): string {
		return substr((string)$timestamp, 0, 19);
	}

	/** A bill's row the app generated, which no statement has checked */
	private static function removable(Transaction $tx): bool {
		return !$tx->getReconciled() && self::bookedForABill($tx);
