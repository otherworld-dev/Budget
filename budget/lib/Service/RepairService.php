	/**
	 * Find liability accounts holding a POSITIVE opening balance that has never
	 * been declared as a genuine credit (#353).
	 *
	 * A liability stores what is owed as a negative number. A positive value is
	 * legal — it means the account is overpaid — but until #353 the edit form
	 * accepted a positive figure with no way to say which was meant, so a user
	 * who typed their statement balance without the minus sign silently doubled
	 * the account into their net worth.
	 *
	 * liability_in_credit === true means the user has explicitly declared this
	 * one a real overpayment, so it is never reported again and this category
	 * drains to empty instead of firing forever.
	 */
	private function findLiabilitySignFlipped(string $userId): array {
		$accounts = $this->accountMapper->findAll($userId);
		$flipped = [];

		foreach ($accounts as $account) {
			$type = AccountType::tryFrom((string)$account->getType());
			if ($type === null || !$type->isLiability()) {
				continue;
			}
			if ($account->getLiabilityInCredit() === true) {
				// Declared a genuine overpayment — leave it alone.
				continue;
			}

			$opening = (float)($account->getOpeningBalance() ?? 0);
			if ($opening <= 0.005) {
				continue;
			}

			$accountId = $account->getId();
			$net = $this->transactionMapper->getNetChangeAll($accountId);

			$flipped[] = [
				'accountId' => $accountId,
				'accountName' => $account->getName(),
				'accountType' => $account->getType(),
				'currency' => $account->getCurrency(),
				'openingBalance' => round($opening, 2),
				'repairedOpeningBalance' => round(-$opening, 2),
				// The figures the user recognises: what the account reads now,
				// and what it will read afterwards. opening_balance is not a
				// number most people have ever looked at.
				'currentBalance' => round($opening + $net, 2),
				'repairedBalance' => round(-$opening + $net, 2),
			];
		}

		// Biggest first: a 12,000 "credit" on a mortgage is obviously a typo,
		// a 43 credit on a card plausibly is not.
		usort($flipped, fn ($a, $b) => $b['openingBalance'] <=> $a['openingBalance']);

		return $flipped;
	}

	/**
	 * Re-sign liability opening balances that were entered without the minus,
	 * and record the user's decision so neither outcome is asked about again (#353).
	 *
	 * $accountIds names the accounts to FIX. Every other detected account was
	 * deselected in the preview, which means "this one is a genuine
	 * overpayment" — so it is marked liability_in_credit = true and drops out
	 * of the detector permanently. Passing null fixes everything found, which
	 * is what a caller sending only a category list means.
	 *
	 * ORDER MATTERS: opening_balance is rewritten FIRST and the balance is then
	 * re-derived by recalculateAllBalances (balance = opening_balance + net).
	 * Do NOT "fix" this to preserve the displayed balance — the corruption lives
	 * in opening_balance itself. That is also why these rows were never caught:
	 * they already satisfy the ledger invariant, so findBalanceDrift passes them.
	 */
	private function repairLiabilitySignFlipped(string $userId, ?array $accountIds = null): array {
		$found = $this->findLiabilitySignFlipped($userId);
		$fixed = 0;
		$confirmed = 0;

		foreach ($found as $item) {
			$shouldFix = $accountIds === null || in_array($item['accountId'], $accountIds, true);

			try {
				$account = $this->accountMapper->findById($item['accountId']);
				if (!$account) {
					continue;
				}
				$opening = (float)($account->getOpeningBalance() ?? 0);
				if ($opening <= 0.005) {
					// Changed under us since the scan
					continue;
				}

				if ($shouldFix) {
					$account->setOpeningBalance(-$opening);
					$account->setLiabilityInCredit(false);
					$fixed++;
				} else {
					// Deselected: the user says this really is an overpayment.
					$account->setLiabilityInCredit(true);
					$confirmed++;
				}
				$account->setUpdatedAt(date('Y-m-d H:i:s'));
				$this->accountMapper->update($account);
			} catch (\Exception $e) {
				// Skip on error
			}
		}

		// Re-derive balance from the corrected opening_balance.
		if ($fixed > 0) {
			$this->accountService->recalculateAllBalances($userId);
		}

		return ['fixed' => $fixed, 'confirmed' => $confirmed, 'found' => count($found)];
	}

	/**
	 * Find accounts where stored balance differs from calculated balance.
	 */
	private function findBalanceDrift(string $userId): array {
		$accounts = $this->accountMapper->findAll($userId);
		$drifted = [];

		foreach ($accounts as $account) {
			$accountId = $account->getId();
			$storedBalance = (float)$account->getBalance();
			// The same figure the repair (recalculateAllBalances) will write,
			// so what is reported and what is fixed never disagree.
			$expectedBalance = MoneyCalculator::toFloat($this->balanceCalculator->expectedBalance($account));

			$diff = abs($expectedBalance - $storedBalance);
			if ($diff > 0.005) {
				$drifted[] = [
					'accountId' => $accountId,
					'accountName' => $account->getName(),
					'storedBalance' => round($storedBalance, 2),
					'expectedBalance' => round($expectedBalance, 2),
					'difference' => round($expectedBalance - $storedBalance, 2),
				];
			}
		}

		return $drifted;
	}

	/**
	 * Delete duplicate bill payments and return the count.
	 *
	 * @param int[]|null $transactionIds The rows the user ticked in the
	 *                                   preview. Null, from a caller that names
	 *                                   none, removes only the duplicates the
	 *                                   scan is sure of ('selected').
	 */
	private function repairDuplicateAutoGenerated(string $userId, ?array $transactionIds = null): array {
		$duplicates = $this->findDuplicateAutoGenerated($userId);
		$wanted = $transactionIds !== null ? array_flip($transactionIds) : null;
		$deleted = 0;

		// Make sure every pair keeps one half.
		//
		// The detectors run over the same rows and could each pick a
		// different keeper, and a pair flagged in both directions once had
		// BOTH halves deleted - the payment went with the duplicate. So a row
		// already kept is never deleted, and when the row a finding points at
		// as its original is itself going, the finding is left for the next
		// run rather than guessed at. Under-deleting is the safe direction
		// for a repair tool.
		$seen = [];
		$keep = [];
		foreach ($duplicates as $dup) {
			$id = $dup['duplicateId'];
			// Only what this scan found itself: an id in the request that
			// matches none of its findings is never deleted
			if ($wanted !== null ? !isset($wanted[$id]) : !$dup['selected']) {
				continue;
			}
			$originalId = $dup['originalId'] ?? null;
			if (isset($seen[$id]) || isset($keep[$id])) {
				continue;
			}
			if ($originalId !== null && isset($seen[$originalId])) {
				continue;
			}
			if ($originalId !== null) {
				$keep[$originalId] = true;
			}
			$seen[$id] = true;

			try {
				// A row reconciled since the scan was checked against a
				// statement: it stays
				$row = $this->transactionMapper->findById($id);
				if ($row === null || $row->getReconciled()) {
					continue;
				}
				// Through the service, never the mapper. Splits, tags,
				// attachments and expense shares hang off a transaction with
				// no foreign keys behind them, so a bare mapper delete leaves
				// them orphaned permanently - nothing can surface them and
				// nothing can reclaim them, factory reset included (#359).
				// Under the account owner, since a duplicate can sit in a
				// shared account (#334). A transfer's withdrawal is deleted
				// as its bill's row, which takes the deposit the bill booked
				// with it.
				$removed = ($dup['transfer'] ?? false) && $dup['billId'] !== null
					? $this->transactionService->deleteAsAccountOwner($id, false, (int)$dup['billId'])
					: $this->transactionService->deleteAsAccountOwner($id);
				if ($removed) {
					$deleted++;
					if (isset($dup['paidDateAfterRepair']) && $dup['billId'] !== null) {
						$this->keepOneTimeBillPaid($userId, (int)$dup['billId'], $dup['paidDateAfterRepair']);
					}
				}
			} catch (\Exception $e) {
				// Transaction may already be deleted, skip
			}
		}

		// Recompute balances from the ledger after removing cleared duplicates
		if ($deleted > 0) {
			$this->accountService->recalculateAllBalances($userId);
		}

		return ['deleted' => $deleted, 'found' => count($duplicates)];
	}

	/**
	 * A one-time bill paid twice, once the newer payment is gone: paid on the
	 * date of the one left, and completed. Its undo snapshot describes the
	 * payment just removed, and Mark Unpaid from it would re-open a bill that
	 * is paid, so it goes too.
	 */
	private function keepOneTimeBillPaid(string $userId, int $billId, string $paidDate): void {
		$this->billMapper->updateFields($billId, $userId, [
			'last_paid_date' => $paidDate,
			'is_active' => false,
			'next_due_date' => null,
			'paid_undo_state' => null,
		]);
	}

	/**
	 * Move a stuck bill on to the occurrence after the one its last payment
	 * settled, or a far-future date back onto its schedule, and take its
	 * pending row along. Bills only listed for checking are left alone.
	 */
	private function repairStuckBills(string $userId): array {
		$stuck = $this->findStuckBills($userId);
		$today = $this->today($userId);
		$fixed = 0;

		foreach ($stuck as $item) {
			if (!$item['fixable']) {
				continue;
			}
			try {
				$bill = $this->billMapper->find($item['billId'], $userId);

				// One occurrence past the one the last payment settled. A
				// far-future date without that knowledge is worked out afresh
				// from today rather than advanced from the broken date. The
				// bill's startDate anchors weekly/biweekly parity either way
				// (#364).
				$settled = $item['settledOccurrence'];
				$isFarFuture = $item['reason'] === 'far_future_due_date';
				$nextDue = $this->frequencyCalculator->calculateNextDueDate(
					$bill->getFrequency(),
					$bill->getDueDay(),
					$bill->getDueMonth(),
					$settled,
					$bill->getCustomRecurrencePattern(),
					$settled !== null,
					$bill->getStartDate(),
					$today
				);

				// Only update if it actually moved: on past the settled
				// occurrence, or back from the far future
				if ($nextDue === $bill->getNextDueDate() || (!$isFarFuture && $nextDue < $bill->getNextDueDate())) {
					continue;
				}
				$bill->setNextDueDate($nextDue);
				$this->billMapper->update($bill);
				$this->movePendingRows($bill, $nextDue);
				$fixed++;
			} catch (\Exception $e) {
				// Skip bills that can't be fixed
			}
		}

		return ['fixed' => $fixed, 'found' => count($stuck)];
	}

	/**
	 * Move a bill's pending row(s) to its new due date. Left on the old date
	 * they stand for an occurrence the bill no longer shows as due, and the
	 * next payment books it there. Moved rather than recreated, so splits and
	 * tags on them stay.
	 */
	private function movePendingRows(Bill $bill, string $nextDue): void {
		foreach ($this->transactionMapper->findAllScheduledByBillId($bill->getId()) as $row) {
			if ($row->getDate() === $nextDue) {
				continue;
			}
			try {
				$owner = $this->accountMapper->findById($row->getAccountId())->getUserId();
				$this->transactionService->update($row->getId(), $owner, ['date' => $nextDue]);
			} catch (\Exception $e) {
				// Left for the bill's next payment to settle
			}
		}
	}

	/**
	 * Find one-time bills that have been paid but are still active.
	 *
	 * Paid means paid by its date: the paid date, or a payment recorded for
	 * the bill, within ONE_TIME_PAYMENT_DAYS of it, as editing the bill
	 * judges it. A bill switched to one-time keeps the date it last paid an
	 * occurrence of its old schedule, and is still due on its own date
	 * (#399); the repair comes ticked, so a bill still owed must not be
	 * listed. One with no due date left, as older versions left a paid one
	 * (#163), has nothing left to pay, whenever it was paid.
	 */
	private function findPaidOneTimeBillsStillActive(string $userId): array {
		$bills = array_values(array_filter(
			$this->billMapper->findActive($userId),
			fn (Bill $bill) => $bill->getFrequency() === 'one-time' && $bill->getLastPaidDate()
		));
		$near = fn (string $day, string $date): bool => self::daysApart($day, $date) <= self::ONE_TIME_PAYMENT_DAYS;
		$paid = [];
		$unsure = [];
		foreach ($bills as $bill) {
			$date = (string)$bill->getNextDueDate();
			if ($date === '' || $near((string)$bill->getLastPaidDate(), $date)) {
				$paid[$bill->getId()] = true;
			} else {
				$unsure[$bill->getId()] = $date;
			}
		}
		// The paid date can be an older payment's, such as the last one of
		// the schedule the bill had before: a payment recorded for the bill
		// by its date pays it all the same
		if ($unsure !== []) {
			foreach ($this->transactionMapper->findRecordedByBillIds(array_keys($unsure)) as $tx) {
				$date = $unsure[(int)$tx->getBillId()] ?? null;
				if ($date !== null && $near((string)$tx->getDate(), $date)) {
					$paid[(int)$tx->getBillId()] = true;
				}
			}
		}
		$found = [];

		foreach ($bills as $bill) {
			if (!isset($paid[$bill->getId()])) {
				continue;
			}
			// Paid, and still active: should be completed
			$found[] = [
				'billId' => $bill->getId(),
				'name' => $bill->getName(),
				'amount' => (float)$bill->getAmount(),
				'lastPaidDate' => $bill->getLastPaidDate(),
				'nextDueDate' => $bill->getNextDueDate(),
			];
		}

		return $found;
	}

	/**
	 * Deactivate paid one-time bills and clear their nextDueDate.
	 */
	private function repairPaidOneTimeBills(string $userId): array {
		$found = $this->findPaidOneTimeBillsStillActive($userId);
		$fixed = 0;

		foreach ($found as $item) {
			try {
				$bill = $this->billMapper->find($item['billId'], $userId);
				$bill->setIsActive(false);
				$bill->setNextDueDate(null);
				$this->billMapper->update($bill);
				$fixed++;
			} catch (\Exception $e) {
				// Skip on error
			}
		}

		return ['fixed' => $fixed, 'found' => count($found)];
	}

	/**
	 * Find recurring income 2.54.0 left due on a receipt it had already
	 * booked (LegacyIncomeRows::stuckEarlyReceipts()), so the next Mark
	 * Received would book the money again. The upgrade settles the ones it
	 * finds; a backup restored since brings them back.
	 */
	private function findStuckIncome(string $userId): array {
		if ($this->legacyIncomeRows === null) {
			return [];
		}
		return array_map(fn (array $stuck) => [
			'incomeId' => $stuck['incomeId'],
			'name' => $stuck['name'],
			'amount' => $stuck['amount'],
			'transactionId' => $stuck['transactionId'],
			'lastReceivedDate' => $stuck['lastReceivedDate'],
			'nextExpectedDate' => $stuck['nextExpectedDate'],
			'settledNextExpectedDate' => $stuck['settledNextExpectedDate'],
		], $this->legacyIncomeRows->stuckEarlyReceipts($userId));
	}

	/**
	 * Move each stuck income on to its next expected date. Nothing is booked
	 * or deleted: the receipt is already in the ledger.
	 */
	private function repairStuckIncome(string $userId): array {
		if ($this->legacyIncomeRows === null) {
			return ['fixed' => 0, 'found' => 0];
		}
		$found = $this->legacyIncomeRows->stuckEarlyReceipts($userId);
		$fixed = 0;

		foreach ($found as $stuck) {
			try {
				if ($this->legacyIncomeRows->settle($stuck)) {
					$fixed++;
				}
			} catch (\Exception $e) {
				// Skip on error
			}
		}

		return ['fixed' => $fixed, 'found' => count($found)];
	}
