<?php

declare(strict_types=1);

namespace OCA\Budget\Service;

use OCA\Budget\Db\AccountMapper;
use OCA\Budget\Db\BillMapper;
use OCA\Budget\Db\TransactionMapper;
use OCA\Budget\Service\Bill\FrequencyCalculator;
use OCA\Budget\Enum\AccountType;
use OCA\Budget\Service\MoneyCalculator;

/**
 * Diagnoses and repairs data integrity issues.
 */
class RepairService {
    /**
     * Every repair category id, in the order diagnose() reports them.
     * SetupController validates the request against this rather than keeping its
     * own literal copy — a category added here is immediately accepted.
     */
    public const CATEGORIES = [
        'duplicateTransactions',
        'stuckBills',
        'paidOneTimeBills',
        'futureClearedTransactions',
        'transferCreditCategories',
        'liabilitySignFlipped',
        'splitParentCategories',
        'balanceDrift',
    ];

    private TransactionMapper $transactionMapper;
    private BillMapper $billMapper;
    private AccountMapper $accountMapper;
    private FrequencyCalculator $frequencyCalculator;
    private AccountService $accountService;

    public function __construct(
        TransactionMapper $transactionMapper,
        BillMapper $billMapper,
        AccountMapper $accountMapper,
        FrequencyCalculator $frequencyCalculator,
        AccountService $accountService
    ) {
        $this->transactionMapper = $transactionMapper;
        $this->billMapper = $billMapper;
        $this->accountMapper = $accountMapper;
        $this->frequencyCalculator = $frequencyCalculator;
        $this->accountService = $accountService;
    }

    /**
     * Diagnose data integrity issues without making any changes.
     *
     * @return array Categorized findings
     */
    public function diagnose(string $userId): array {
        return [
            'duplicateTransactions' => $this->findDuplicateAutoGenerated($userId),
            'stuckBills' => $this->findStuckBills($userId),
            'paidOneTimeBills' => $this->findPaidOneTimeBillsStillActive($userId),
            'futureClearedTransactions' => $this->findFutureClearedTransactions($userId),
            // Transfer credits now correctly preserve categories (since v2.26.3)
            'transferCreditCategories' => [],
            'liabilitySignFlipped' => $this->findLiabilitySignFlipped($userId),
            'splitParentCategories' => $this->findCategorisedSplitParents($userId),
            'balanceDrift' => $this->findBalanceDrift($userId),
        ];
    }

    /**
     * Repair specific categories of issues.
     *
     * @param string[] $categories Which categories to fix: 'duplicateTransactions', 'stuckBills', 'balanceDrift'
     * @return array Results per category
     */
    public function repair(string $userId, array $categories, array $options = []): array {
        $results = [];

        if (in_array('duplicateTransactions', $categories)) {
            $results['duplicateTransactions'] = $this->repairDuplicateAutoGenerated($userId);
        }

        if (in_array('stuckBills', $categories)) {
            $results['stuckBills'] = $this->repairStuckBills($userId);
        }

        if (in_array('paidOneTimeBills', $categories)) {
            $results['paidOneTimeBills'] = $this->repairPaidOneTimeBills($userId);
        }

        if (in_array('futureClearedTransactions', $categories)) {
            $results['futureClearedTransactions'] = $this->repairFutureClearedTransactions($userId);
        }

        // transferCreditCategories repair removed — credits now correctly keep categories

        if (in_array('liabilitySignFlipped', $categories)) {
            $results['liabilitySignFlipped'] = $this->repairLiabilitySignFlipped(
                $userId,
                isset($options['accountIds']) && is_array($options['accountIds'])
                    ? array_map('intval', $options['accountIds'])
                    : null
            );
        }

        if (in_array('splitParentCategories', $categories)) {
            $results['splitParentCategories'] = $this->repairCategorisedSplitParents($userId);
        }

        // Balance recalculation should always run last (after tx cleanup)
        if (in_array('balanceDrift', $categories)) {
            $results['balanceDrift'] = $this->accountService->recalculateAllBalances($userId);
        }

        return $results;
    }

    /**
     * Find duplicate auto-generated transactions.
     * These are "next occurrence" transactions that should have been scheduled
     * but ended up as cleared duplicates of manually-entered payments.
     */
    private function findDuplicateAutoGenerated(string $userId): array {
        $accounts = $this->accountMapper->findAll($userId);
        $duplicates = [];

        foreach ($accounts as $account) {
            $accountId = $account->getId();

            // Get all auto-generated cleared transactions for this account
            $autoGen = $this->transactionMapper->findAutoGeneratedBillTransactions($accountId);

            // Exclude future-dated transactions (those are handled by futureClearedTransactions)
            $today = date('Y-m-d');
            $autoGen = array_values(array_filter($autoGen, fn($tx) => $tx->getDate() <= $today));

            // Group by (amount, created_at) to find pairs created by markPaid
            $groups = [];
            foreach ($autoGen as $tx) {
                $key = $tx->getAmount() . '|' . $tx->getCreatedAt();
                $groups[$key][] = $tx;
            }

            // Pairs where same amount+created_at have different dates = duplicate from markPaid
            // Only flag if dates are close together (<= 14 days). Entries that are a full
            // billing cycle apart (e.g., 30 days for monthly) are legitimate payment +
            // next occurrence pairs, not duplicates.
            foreach ($groups as $group) {
                if (count($group) < 2) {
                    continue;
                }

                usort($group, fn($a, $b) => strcmp($a->getDate(), $b->getDate()));
                $original = $group[0];
                for ($i = 1; $i < count($group); $i++) {
                    $candidate = $group[$i];
                    $daysBetween = abs((strtotime($candidate->getDate()) - strtotime($original->getDate())) / 86400);
                    if ($daysBetween > 14) {
                        continue; // Different billing cycles, not a duplicate
                    }
                    $duplicates[] = [
                        'duplicateId' => $candidate->getId(),
                        'originalId' => $original->getId(),
                        'amount' => (float) $candidate->getAmount(),
                        'date' => $candidate->getDate(),
                        'originalDate' => $original->getDate(),
                        'vendor' => $candidate->getVendor(),
                        'accountId' => $accountId,
                        'accountName' => $account->getName(),
                    ];
                }
            }

            // Find stale "next occurrence" transactions from a previous markPaid cycle
            // that weren't cleaned up (different created_at but same bill+month)
            $this->findSameBillDuplicatesInPeriod($autoGen, $duplicates, $account->getName(), $accountId);

            // Also find auto-generated transactions that duplicate a manually-entered one
            // (same account, similar date, auto-gen notes, and a manual tx with same vendor exists)
            $this->findAutoGenDuplicatesOfManualEntries($accountId, $autoGen, $duplicates, $account->getName());
        }

        return $duplicates;
    }

    /**
     * Find auto-generated transactions for the same bill that appear multiple
     * times in the same billing period. This catches stale "next occurrence"
     * transactions from a previous markPaid that weren't cleaned up.
     */
    private function findSameBillDuplicatesInPeriod(array $autoGen, array &$duplicates, string $accountName, int $accountId): void {
        // Already-flagged IDs (from the created_at grouping above)
        $alreadyFlagged = [];
        foreach ($duplicates as $dup) {
            $alreadyFlagged[$dup['duplicateId']] = true;
        }

        // Group by bill name (from notes) + amount + month
        $groups = [];
        foreach ($autoGen as $tx) {
            $notes = $tx->getNotes() ?? '';
            if (!preg_match('/^Auto-generated from bill: (.+)$/', $notes, $m)) {
                continue;
            }
            $billName = trim($m[1]);
            $month = substr($tx->getDate(), 0, 7); // YYYY-MM
            $key = $billName . '|' . $tx->getAmount() . '|' . $month;
            $groups[$key][] = $tx;
        }

        foreach ($groups as $group) {
            if (count($group) < 2) {
                continue;
            }

            // The most recent created_at is likely the correct payment;
            // older created_at entries are stale "next occurrences" that got stuck
            usort($group, fn($a, $b) => strcmp($a->getCreatedAt(), $b->getCreatedAt()));
            $correct = end($group);

            foreach ($group as $tx) {
                if ($tx->getId() === $correct->getId()) {
                    continue;
                }
                if (isset($alreadyFlagged[$tx->getId()])) {
                    continue;
                }
                $duplicates[] = [
                    'duplicateId' => $tx->getId(),
                    'originalId' => $correct->getId(),
                    'amount' => (float) $tx->getAmount(),
                    'date' => $tx->getDate(),
                    'originalDate' => $correct->getDate(),
                    'vendor' => $tx->getVendor() ?: $correct->getVendor(),
                    'accountId' => $accountId,
                    'accountName' => $accountName,
                    'reason' => 'stale_next_occurrence',
                ];
            }
        }
    }

    /**
     * Find auto-generated transactions that duplicate manually-entered ones.
     */
    private function findAutoGenDuplicatesOfManualEntries(int $accountId, array $autoGen, array &$duplicates, string $accountName): void {
        foreach ($autoGen as $tx) {
            $vendor = $tx->getVendor();
            if (empty($vendor)) {
                continue;
            }

            // Look for a non-auto-generated transaction with the same vendor, within ±3 days
            $startDate = date('Y-m-d', strtotime($tx->getDate() . ' -3 days'));
            $endDate = date('Y-m-d', strtotime($tx->getDate() . ' +3 days'));
            $candidates = $this->transactionMapper->findByDateRange($accountId, $startDate, $endDate);

            foreach ($candidates as $candidate) {
                if ($candidate->getId() === $tx->getId()) {
                    continue;
                }
                // Skip other auto-generated ones
                $notes = $candidate->getNotes() ?? '';
                if (str_starts_with($notes, 'Auto-generated')) {
                    continue;
                }
                // Match by vendor or description
                $candVendor = mb_strtolower(trim($candidate->getVendor() ?? ''));
                $candDesc = mb_strtolower(trim($candidate->getDescription() ?? ''));
                $billName = mb_strtolower(trim($vendor));

                if ($candVendor === $billName || $candDesc === $billName
                    || str_contains($candVendor, $billName) || str_contains($candDesc, $billName)) {
                    // Check amount is in the same ballpark (within 25%)
                    $txAmt = (float) $tx->getAmount();
                    $candAmt = (float) $candidate->getAmount();
                    if ($txAmt > 0 && abs($txAmt - $candAmt) / $txAmt <= 0.25) {
                        $duplicates[] = [
                            'duplicateId' => $tx->getId(),
                            'originalId' => $candidate->getId(),
                            'amount' => $txAmt,
                            'date' => $tx->getDate(),
                            'originalDate' => $candidate->getDate(),
                            'vendor' => $vendor,
                            'accountId' => $accountId,
                            'accountName' => $accountName,
                            'reason' => 'auto_gen_duplicates_manual',
                        ];
                        break; // Only flag once per auto-gen tx
                    }
                }
            }
        }
    }

    /**
     * Find bills with stuck nextDueDate (didn't advance after payment).
     */
    private function findStuckBills(string $userId): array {
        $bills = $this->billMapper->findActive($userId);
        $stuck = [];
        $today = date('Y-m-d');

        foreach ($bills as $bill) {
            // One-time bills are handled by paidOneTimeBills, not here
            if ($bill->getFrequency() === 'one-time') {
                continue;
            }

            $lastPaid = $bill->getLastPaidDate();
            $nextDue = $bill->getNextDueDate();

            if (!$lastPaid || !$nextDue) {
                continue;
            }

            // Bill is stuck if it was paid but nextDueDate didn't advance.
            // For recurring bills, nextDueDate should be at least ~14 days after lastPaidDate.
            // If nextDue is within 7 days of lastPaid, it almost certainly didn't advance.
            $isStuck = false;
            $reason = '';
            $daysBetween = (strtotime($nextDue) - strtotime($lastPaid)) / 86400;
            $frequency = $bill->getFrequency();

            if ($nextDue <= $lastPaid) {
                $isStuck = true;
                $reason = 'next_due_before_paid';
            } elseif (!in_array($frequency, ['one-time', 'daily', 'weekly', 'biweekly']) && $daysBetween <= 7 && $lastPaid >= date('Y-m-d', strtotime('-60 days'))) {
                // For monthly+ bills, nextDue should be further out than 7 days from payment
                $isStuck = true;
                $reason = 'next_due_not_advanced';
            } elseif ($nextDue <= $today && $lastPaid >= date('Y-m-d', strtotime('-30 days'))) {
                $isStuck = true;
                $reason = 'overdue_despite_recent_payment';
            } elseif ($nextDue > date('Y-m-d', strtotime('+10 years'))) {
                // Far-future date from broken forceAdvance calculation
                $isStuck = true;
                $reason = 'far_future_due_date';
            }

            if ($isStuck) {
                $stuck[] = [
                    'billId' => $bill->getId(),
                    'name' => $bill->getName(),
                    'frequency' => $bill->getFrequency(),
                    'nextDueDate' => $nextDue,
                    'lastPaidDate' => $lastPaid,
                    'reason' => $reason,
                ];
            }
        }

        return $stuck;
    }

    /**
     * Find future-dated transactions incorrectly marked as cleared.
     */
    private function findFutureClearedTransactions(string $userId): array {
        $accounts = $this->accountMapper->findAll($userId);
        $found = [];
        $today = date('Y-m-d');

        foreach ($accounts as $account) {
            $transactions = $this->transactionMapper->findByDateRange(
                $account->getId(),
                date('Y-m-d', strtotime('+1 day')),
                date('Y-m-d', strtotime('+5 years'))
            );

            foreach ($transactions as $tx) {
                $status = $tx->getStatus() ?? 'cleared';
                if ($status === 'cleared' && $tx->getDate() > $today) {
                    $found[] = [
                        'transactionId' => $tx->getId(),
                        'date' => $tx->getDate(),
                        'amount' => (float) $tx->getAmount(),
                        'type' => $tx->getType(),
                        'description' => $tx->getDescription() ?: $tx->getVendor() ?: '',
                        'accountId' => $account->getId(),
                        'accountName' => $account->getName(),
                    ];
                }
            }
        }

        return $found;
    }

    /**
     * Fix future-dated cleared transactions by setting them to scheduled
     * and reversing their balance impact.
     */
    private function repairFutureClearedTransactions(string $userId): array {
        $found = $this->findFutureClearedTransactions($userId);
        $fixed = 0;

        foreach ($found as $item) {
            try {
                $tx = $this->transactionMapper->findById($item['transactionId']);
                if (!$tx || $tx->getStatus() === 'scheduled') {
                    continue;
                }

                // Change to scheduled
                $tx->setStatus('scheduled');
                $tx->setUpdatedAt(date('Y-m-d H:i:s'));
                $this->transactionMapper->update($tx);

                $fixed++;
            } catch (\Exception $e) {
                // Skip on error
            }
        }

        // Recompute balances from the ledger (scheduled rows no longer count)
        if ($fixed > 0) {
            $this->accountService->recalculateAllBalances($userId);
        }

        return ['fixed' => $fixed, 'found' => count($found)];
    }

    /**
     * Find credit-side transfer transactions that still have a category assigned.
     * The credit side of a transfer should not carry a category — only the debit
     * side represents spending in that category.
     */
    private function findTransferCreditsWithCategory(string $userId): array {
        $accounts = $this->accountMapper->findAll($userId);
        $found = [];

        foreach ($accounts as $account) {
            $transactions = $this->transactionMapper->findLinkedCreditsWithCategory($account->getId());
            foreach ($transactions as $tx) {
                $found[] = [
                    'transactionId' => $tx->getId(),
                    'date' => $tx->getDate(),
                    'amount' => (float) $tx->getAmount(),
                    'categoryId' => $tx->getCategoryId(),
                    'vendor' => $tx->getVendor() ?: $tx->getDescription() ?: '',
                    'accountId' => $account->getId(),
                    'accountName' => $account->getName(),
                ];
            }
        }

        return $found;
    }

    /**
     * Clear category_id on credit-side transfer transactions.
     */
    private function repairTransferCreditCategories(string $userId): array {
        $found = $this->findTransferCreditsWithCategory($userId);
        $fixed = 0;

        foreach ($found as $item) {
            try {
                $tx = $this->transactionMapper->findById($item['transactionId']);
                if ($tx && $tx->getCategoryId() !== null) {
                    $tx->setCategoryId(null);
                    $tx->setUpdatedAt(date('Y-m-d H:i:s'));
                    $this->transactionMapper->update($tx);
                    $fixed++;
                }
            } catch (\Exception $e) {
                // Skip on error
            }
        }

        return ['fixed' => $fixed, 'found' => count($found)];
    }

    /**
     * Find split transactions that also carry a category of their own (#360).
     *
     * A split's categories live on its parts and its own must be empty. The old
     * bulk edit wrote one anyway, and so did every rule run until #360, leaving
     * rows that claim a category while still carrying their own breakdown. The
     * aggregates no longer double-count them, but the stale category is still
     * there, and anything reading category_id directly still reads it.
     */
    private function findCategorisedSplitParents(string $userId): array {
        $found = [];

        foreach ($this->transactionMapper->findCategorisedSplitParents($userId) as $tx) {
            $found[] = [
                'transactionId' => $tx->getId(),
                'date' => $tx->getDate(),
                'amount' => (float) $tx->getAmount(),
                'categoryId' => $tx->getCategoryId(),
                'description' => $tx->getDescription() ?: '',
                'vendor' => $tx->getVendor() ?: '',
            ];
        }

        return $found;
    }

    /**
     * Clear the stale category off a split transaction, leaving its parts alone
     * — they hold the real categories and are what every total now reads.
     */
    private function repairCategorisedSplitParents(string $userId): array {
        $found = $this->findCategorisedSplitParents($userId);
        $fixed = 0;

        foreach ($found as $item) {
            try {
                $tx = $this->transactionMapper->findById($item['transactionId']);
                if ($tx && $tx->getCategoryId() !== null) {
                    $tx->setCategoryId(null);
                    $tx->setUpdatedAt(date('Y-m-d H:i:s'));
                    $this->transactionMapper->update($tx);
                    $fixed++;
                }
            } catch (\Exception $e) {
                // Skip on error
            }
        }

        return ['fixed' => $fixed, 'found' => count($found)];
    }

    /**
     * Find liability accounts holding a POSITIVE opening balance that has never
     * been declared as a genuine credit (#353).
     *
     * A liability stores what is owed as a negative number. A positive value is
     * legal — it means the account is overpaid — but until #353 the edit form
     * accepted a positive figure with no way to say which was meant, so a user
     * who typed their statement balance without the minus sign silently doubled
     * the account into their net worth.
     *
     * liability_in_credit === true means the user has explicitly declared this
     * one a real overpayment, so it is never reported again and this category
     * drains to empty instead of firing forever.
     */
    private function findLiabilitySignFlipped(string $userId): array {
        $accounts = $this->accountMapper->findAll($userId);
        $flipped = [];

        foreach ($accounts as $account) {
            $type = AccountType::tryFrom((string) $account->getType());
            if ($type === null || !$type->isLiability()) {
                continue;
            }
            if ($account->getLiabilityInCredit() === true) {
                // Declared a genuine overpayment — leave it alone.
                continue;
            }

            $opening = (float) ($account->getOpeningBalance() ?? 0);
            if ($opening <= 0.005) {
                continue;
            }

            $accountId = $account->getId();
            $net = $this->transactionMapper->getNetChangeAll($accountId);

            $flipped[] = [
                'accountId' => $accountId,
                'accountName' => $account->getName(),
                'accountType' => $account->getType(),
                'currency' => $account->getCurrency(),
                'openingBalance' => round($opening, 2),
                'repairedOpeningBalance' => round(-$opening, 2),
                // The figures the user recognises: what the account reads now,
                // and what it will read afterwards. opening_balance is not a
                // number most people have ever looked at.
                'currentBalance' => round($opening + $net, 2),
                'repairedBalance' => round(-$opening + $net, 2),
            ];
        }

        // Biggest first: a 12,000 "credit" on a mortgage is obviously a typo,
        // a 43 credit on a card plausibly is not.
        usort($flipped, fn($a, $b) => $b['openingBalance'] <=> $a['openingBalance']);

        return $flipped;
    }

    /**
     * Re-sign liability opening balances that were entered without the minus,
     * and record the user's decision so neither outcome is asked about again (#353).
     *
     * $accountIds names the accounts to FIX. Every other detected account was
     * deselected in the preview, which means "this one is a genuine
     * overpayment" — so it is marked liability_in_credit = true and drops out
     * of the detector permanently. Passing null fixes everything found, which
     * is what a caller sending only a category list means.
     *
     * ORDER MATTERS: opening_balance is rewritten FIRST and the balance is then
     * re-derived by recalculateAllBalances (balance = opening_balance + net).
     * Do NOT "fix" this to preserve the displayed balance — the corruption lives
     * in opening_balance itself. That is also why these rows were never caught:
     * they already satisfy the ledger invariant, so findBalanceDrift passes them.
     */
    private function repairLiabilitySignFlipped(string $userId, ?array $accountIds = null): array {
        $found = $this->findLiabilitySignFlipped($userId);
        $fixed = 0;
        $confirmed = 0;

        foreach ($found as $item) {
            $shouldFix = $accountIds === null || in_array($item['accountId'], $accountIds, true);

            try {
                $account = $this->accountMapper->findById($item['accountId']);
                if (!$account) {
                    continue;
                }
                $opening = (float) ($account->getOpeningBalance() ?? 0);
                if ($opening <= 0.005) {
                    // Changed under us since the scan
                    continue;
                }

                if ($shouldFix) {
                    $account->setOpeningBalance(-$opening);
                    $account->setLiabilityInCredit(false);
                    $fixed++;
                } else {
                    // Deselected: the user says this really is an overpayment.
                    $account->setLiabilityInCredit(true);
                    $confirmed++;
                }
                $account->setUpdatedAt(date('Y-m-d H:i:s'));
                $this->accountMapper->update($account);
            } catch (\Exception $e) {
                // Skip on error
            }
        }

        // Re-derive balance from the corrected opening_balance.
        if ($fixed > 0) {
            $this->accountService->recalculateAllBalances($userId);
        }

        return ['fixed' => $fixed, 'confirmed' => $confirmed, 'found' => count($found)];
    }

    /**
     * Find accounts where stored balance differs from calculated balance.
     */
    private function findBalanceDrift(string $userId): array {
        $accounts = $this->accountMapper->findAll($userId);
        $drifted = [];

        foreach ($accounts as $account) {
            $accountId = $account->getId();
            $storedBalance = (float) $account->getBalance();
            $openingBalance = (float) ($account->getOpeningBalance() ?? 0);
            $transactionNet = $this->transactionMapper->getNetChangeAll($accountId);
            $expectedBalance = $openingBalance + $transactionNet;

            $diff = abs($expectedBalance - $storedBalance);
            if ($diff > 0.005) {
                $drifted[] = [
                    'accountId' => $accountId,
                    'accountName' => $account->getName(),
                    'storedBalance' => round($storedBalance, 2),
                    'expectedBalance' => round($expectedBalance, 2),
                    'difference' => round($expectedBalance - $storedBalance, 2),
                ];
            }
        }

        return $drifted;
    }

    /**
     * Delete duplicate auto-generated transactions and return count.
     */
    private function repairDuplicateAutoGenerated(string $userId): array {
        $duplicates = $this->findDuplicateAutoGenerated($userId);
        $deleted = 0;

        // Deduplicate the list (same tx might be flagged multiple ways)
        $seen = [];
        foreach ($duplicates as $dup) {
            $id = $dup['duplicateId'];
            if (isset($seen[$id])) {
                continue;
            }
            $seen[$id] = true;

            try {
                $tx = $this->transactionMapper->findById($id);
                if ($tx) {
                    $this->transactionMapper->delete($tx);
                    $deleted++;
                }
            } catch (\Exception $e) {
                // Transaction may already be deleted, skip
            }
        }

        // Recompute balances from the ledger after removing cleared duplicates
        if ($deleted > 0) {
            $this->accountService->recalculateAllBalances($userId);
        }

        return ['deleted' => $deleted, 'found' => count($seen)];
    }

    /**
     * Fix bills with stuck nextDueDate by recalculating with forceAdvance.
     */
    private function repairStuckBills(string $userId): array {
        $stuck = $this->findStuckBills($userId);
        $fixed = 0;

        foreach ($stuck as $item) {
            try {
                $bill = $this->billMapper->find($item['billId'], $userId);

                // For far-future dates, recalculate from scratch (today) rather
                // than force-advancing from the broken date. The bill's
                // startDate anchors weekly/biweekly parity in that recalc
                // (#364); the forceAdvance path ignores it by design.
                $isFarFuture = $item['reason'] === 'far_future_due_date';
                $nextDue = $this->frequencyCalculator->calculateNextDueDate(
                    $bill->getFrequency(),
                    $bill->getDueDay(),
                    $bill->getDueMonth(),
                    $isFarFuture ? null : $bill->getNextDueDate(),
                    $bill->getCustomRecurrencePattern(),
                    !$isFarFuture, // forceAdvance only for non-far-future
                    $bill->getStartDate()
                );

                // Only update if it actually advanced
                if ($nextDue !== $bill->getNextDueDate()) {
                    $bill->setNextDueDate($nextDue);
                    $this->billMapper->update($bill);
                    $fixed++;
                }
            } catch (\Exception $e) {
                // Skip bills that can't be fixed
            }
        }

        return ['fixed' => $fixed, 'found' => count($stuck)];
    }

    /**
     * Find one-time bills that have been paid but are still active.
     */
    private function findPaidOneTimeBillsStillActive(string $userId): array {
        $bills = $this->billMapper->findActive($userId);
        $found = [];

        foreach ($bills as $bill) {
            if ($bill->getFrequency() !== 'one-time') {
                continue;
            }
            if (!$bill->getLastPaidDate()) {
                continue;
            }
            // One-time bill with lastPaidDate set but still active = should be deactivated
            $found[] = [
                'billId' => $bill->getId(),
                'name' => $bill->getName(),
                'amount' => (float) $bill->getAmount(),
                'lastPaidDate' => $bill->getLastPaidDate(),
                'nextDueDate' => $bill->getNextDueDate(),
            ];
        }

        return $found;
    }

    /**
     * Deactivate paid one-time bills and clear their nextDueDate.
     */
    private function repairPaidOneTimeBills(string $userId): array {
        $found = $this->findPaidOneTimeBillsStillActive($userId);
        $fixed = 0;

        foreach ($found as $item) {
            try {
                $bill = $this->billMapper->find($item['billId'], $userId);
                $bill->setIsActive(false);
                $bill->setNextDueDate(null);
                $this->billMapper->update($bill);
                $fixed++;
            } catch (\Exception $e) {
                // Skip on error
            }
        }

        return ['fixed' => $fixed, 'found' => count($found)];
    }
