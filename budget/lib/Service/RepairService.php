	/**
	 * Match a bill's payments to its settled occurrences (see
	 * findSameOccurrencePayments()) and return the payments left over, each
	 * with the payment holding the occurrence it would have paid.
	 *
	 * @param Transaction[] $rows the bill's payments
	 * @return array<array{0: Transaction, 1: Transaction, 2: string}> [surplus payment, holder, occurrence]
	 */
	private function paymentsSharingAnOccurrence(Bill $bill, array $rows): array {
		usort($rows, fn (Transaction $a, Transaction $b) => [$a->getDate(), $a->getId()] <=> [$b->getDate(), $b->getId()]);
		$early = self::EARLY_PAYMENT_DAYS[$bill->getFrequency()] ?? 15;
		$dates = array_map(fn (Transaction $tx) => $tx->getDate(), $rows);
		$first = min($dates);

		// Settled: up to the last payment, and before the due date of a bill
		// still running
		$until = self::addDays(max($dates), $early);
		$nextDue = $bill->getIsActive() ? $bill->getNextDueDate() : null;
		if ($nextDue !== null && $nextDue !== '') {
			$until = min($until, self::addDays($nextDue, -1));
		}

		$occurrences = array_values($this->frequencyCalculator->occurrencesBetween(
			$bill->getFrequency(),
			$bill->getDueDay(),
			$bill->getDueMonth(),
			self::addDays($first, -400),
			$until,
			$bill->getCustomRecurrencePattern(),
			$bill->getStartDate()
		));
		// The first payment paid the last occurrence due by its date, or a
		// later one; none before it
		$floor = 0;
		foreach ($occurrences as $i => $date) {
			if ($date <= $first) {
				$floor = $i;
			}
		}
		[$pairs, $late] = self::matchPayments($rows, array_slice($occurrences, $floor), $early);

		// Made a few days ahead of the next occurrence, the first payment may
		// be that one's. Taken for the one before, paid a cycle late, it put
		// every later payment a cycle back, and a second payment of one
		// occurrence passed for the next one's (#399: a bill paid a day early
		// from its first payment on). So the next occurrence is tried as well,
		// within half the early window, and kept when the payments then come
		// out less late, a payment left over counting as a whole cycle late.
		// It must not leave the last payment over where the other reading
		// doesn't: that one paid the occurrence before the bill's due date, so
		// a bill always paid a few days before its next due date is paid late,
		// not early. And it must not leave any payment it matches later than
		// the early window: a bill paid weeks late, with one payment on time,
		// is paid late, and the on-time one is no double.
		$ahead = $occurrences[$floor + 1] ?? null;
		if ($ahead !== null && $occurrences[$floor] < $first && $ahead <= self::addDays($first, intdiv($early, 2))) {
			$cycle = self::daysApart($occurrences[$floor], $ahead);
			[$earlyPairs, $earlyLate, $earlyLatest] = self::matchPayments($rows, array_slice($occurrences, $floor + 1), $early);
			$last = end($rows);
			$leavesLastOver = fn (array $found): bool => $found !== [] && end($found)[0] === $last;
			if ($earlyLatest <= $early
				&& $earlyLate + count($earlyPairs) * $cycle < $late + count($pairs) * $cycle
				&& !($leavesLastOver($earlyPairs) && !$leavesLastOver($pairs))) {
				$pairs = $earlyPairs;
			}
		}

		return $pairs;
	}

	/**
	 * Match payments, oldest first, to occurrences in order: each takes the
	 * earliest one still free that it could be paying, as long as it isn't
	 * made more than $early days ahead of it. Late payments, overdue
	 * occurrences caught up on one day and payments made a few days early
	 * all find an occurrence of their own. A payment left without one paid
	 * an occurrence that was already paid, and is paired with the payment
	 * holding it.
	 *
	 * Returns the pairs, the days the matched payments were late in all, and
	 * the most days any one of them was late.
	 *
	 * @param Transaction[] $rows the payments, oldest first
	 * @param string[] $occurrences from the one the first payment paid on
	 * @return array{0: array<array{0: Transaction, 1: Transaction, 2: string}>, 1: int, 2: int}
	 */
	private static function matchPayments(array $rows, array $occurrences, int $early): array {
		$occurrences = array_values($occurrences);
		$pairs = [];
		$late = 0;
		$latest = 0;
		// The payment holding the latest occurrence taken, and that occurrence
		$held = null;
		$next = 0;
		foreach ($rows as $row) {
			if ($next < count($occurrences) && $occurrences[$next] <= self::addDays($row->getDate(), $early)) {
				$held = [$row, $occurrences[$next]];
				if ($row->getDate() > $occurrences[$next]) {
					$days = self::daysApart($row->getDate(), $occurrences[$next]);
					$late += $days;
					$latest = max($latest, $days);
				}
				$next++;
			} elseif ($held !== null) {
				$pairs[] = [$row, $held[0], $held[1]];
			}
		}

		return [$pairs, $late, $latest];
	}

