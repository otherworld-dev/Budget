	/**
	 * The names a generated payment goes by: the bill's, from its notes, and
	 * its vendor, which starts as the same and may have been edited.
	 *
	 * @return string[] lower case
	 */
	private function billNamesOf(Transaction $tx): array {
		$names = [];
		if (preg_match('/^Auto-generated from bill: (.+)$/', $tx->getNotes() ?? '', $m)) {
			$names[] = mb_strtolower(trim($m[1]));
		}
		$names[] = mb_strtolower(trim($tx->getVendor() ?? ''));
		return array_values(array_unique(array_filter($names, fn (string $name) => $name !== '')));
	}

	/**
	 * Whether a row's vendor or description names the bill: equal to the
	 * name, or holding it as whole words, so "BT" doesn't match "DEBT".
	 *
	 * @param string[] $names lower case
	 */
	private function namesBill(Transaction $tx, array $names): bool {
		foreach ([$tx->getVendor(), $tx->getDescription()] as $text) {
			$text = mb_strtolower(trim($text ?? ''));
			if ($text === '') {
				continue;
			}
			foreach ($names as $name) {
				if ($text === $name
					|| preg_match('/(?<![\p{L}\p{N}])' . preg_quote($name, '/') . '(?![\p{L}\p{N}])/u', $text)) {
					return true;
				}
			}
		}
		return false;
	}

	private static function daysApart(string $a, string $b): int {
		return (int)(new \DateTimeImmutable($a))->diff(new \DateTimeImmutable($b))->format('%a');
	}

	/**
	 * The undo snapshot markPaid() leaves on a bill, when it describes the
	 * bill's last payment rather than an earlier one.
	 */
	private function paymentSnapshot(Bill $bill): ?array {
		$raw = $bill->getPaidUndoState();
		$decoded = ($raw !== null && $raw !== '') ? json_decode($raw, true) : null;
		if (!is_array($decoded) || ($decoded['paidDate'] ?? null) !== $bill->getLastPaidDate()) {
			return null;
		}
		return $decoded;
	}

	/** The occurrence the bill's last payment settled, when its snapshot says */
	private function settledOccurrence(Bill $bill): ?string {
		$previous = $this->paymentSnapshot($bill)['previousState'] ?? null;
		$occurrence = is_array($previous) ? ($previous['nextDueDate'] ?? null) : null;
		return is_string($occurrence) && $occurrence !== '' ? $occurrence : null;
	}

	/**
	 * The rows the bill's last payment wrote or linked, from its snapshot.
	 *
	 * @return int[]
	 */
	private function paymentRowIds(Bill $bill): array {
		$snapshot = $this->paymentSnapshot($bill);
		if ($snapshot === null) {
			return [];
		}
		$ids = is_array($snapshot['createdTransactionIds'] ?? null) ? $snapshot['createdTransactionIds'] : [];
		if (isset($snapshot['linkedTransactionId'])) {
			$ids[] = $snapshot['linkedTransactionId'];
		}
		return array_map('intval', array_values(array_filter($ids, 'is_numeric')));
	}

	/**
	 * Every row the bill's undo snapshot names, whichever payment it is
	 * from: what it wrote, linked and pre-booked.
	 *
	 * @return int[]
	 */
	private function snapshotRowIds(Bill $bill): array {
		$raw = $bill->getPaidUndoState();
		$snapshot = ($raw !== null && $raw !== '') ? json_decode($raw, true) : null;
		if (!is_array($snapshot)) {
			return [];
		}
		$ids = [$snapshot['linkedTransactionId'] ?? null];
		foreach (['createdTransactionIds', 'scheduledTransactionIds'] as $key) {
			if (is_array($snapshot[$key] ?? null)) {
				$ids = array_merge($ids, array_values($snapshot[$key]));
			}
		}
		return array_map('intval', array_values(array_filter($ids, 'is_numeric')));
	}

	/**
	 * Find bills whose due date didn't move on past a payment.
	 *
	 * A payment settles exactly one occurrence, and the snapshot markPaid()
	 * leaves on the bill names it. A due date on or before that occurrence is
	 * stuck, and the repair moves it to the occurrence after. Without a
	 * snapshot of the last payment there is no knowing which occurrence it
	 * settled: a due date before the paid date is then just as likely an
	 * overdue bill with one occurrence caught up and the next still owed, so
	 * it is listed for the user to check and never moved. A paid date close
	 * to the next due date, or a bill due today, is how a late payment and an
	 * ordinary due date look, and isn't reported at all.
	 */
	private function findStuckBills(string $userId): array {
		$bills = $this->billMapper->findActive($userId);
		$stuck = [];
		$farFuture = (new \DateTimeImmutable($this->today($userId)))->modify('+10 years')->format('Y-m-d');

		foreach ($bills as $bill) {
			// One-time bills are handled by paidOneTimeBills, not here
			if ($bill->getFrequency() === 'one-time') {
				continue;
			}

			$lastPaid = $bill->getLastPaidDate();
			$nextDue = $bill->getNextDueDate();

			if (!$lastPaid || !$nextDue) {
				continue;
			}

			$settled = $this->settledOccurrence($bill);
			$reason = null;
			$fixable = false;

			if ($nextDue > $farFuture) {
				// Far-future date from an old broken forceAdvance calculation
				$reason = 'far_future_due_date';
				$fixable = true;
			} elseif ($settled !== null) {
				if ($nextDue <= $settled) {
					$reason = 'next_due_not_advanced';
					$fixable = true;
				}
			} elseif ($nextDue < $lastPaid) {
				$reason = 'next_due_before_paid';
			}

			if ($reason !== null) {
				$stuck[] = [
					'billId' => $bill->getId(),
					'name' => $bill->getName(),
					'frequency' => $bill->getFrequency(),
					'nextDueDate' => $nextDue,
					'lastPaidDate' => $lastPaid,
					'reason' => $reason,
					// False: listed for the user to check, never changed by the repair
					'fixable' => $fixable,
					'settledOccurrence' => $settled,
				];
			}
		}

		return $stuck;
	}

	/**
	 * Find future-dated transactions counted in the balance as if they had
	 * already cleared. "Future" is by the user's own calendar.
	 *
	 * A bill's payment is listed but never switched: as 'scheduled' it reads
	 * as the bill's pending row, and the bill's next Mark Paid, Skip or Mark
	 * Unpaid then re-dates or deletes it. A reconciled row was checked
	 * against a statement, so it is listed and left alone too.
	 */
	private function findFutureClearedTransactions(string $userId): array {
		$accounts = $this->accountMapper->findAll($userId);
		$found = [];
		$today = $this->today($userId);

		foreach ($accounts as $account) {
			$transactions = $this->transactionMapper->findByDateRange(
				$account->getId(),
				self::addDays($today, 1),
				(new \DateTimeImmutable($today))->modify('+5 years')->format('Y-m-d')
			);

			foreach ($transactions as $tx) {
				$status = $tx->getStatus() ?? 'cleared';
				if ($status === 'cleared' && $tx->getDate() > $today) {
					$found[] = [
						'transactionId' => $tx->getId(),
						'date' => $tx->getDate(),
						'amount' => (float)$tx->getAmount(),
						'type' => $tx->getType(),
						'description' => $tx->getDescription() ?: $tx->getVendor() ?: '',
						'accountId' => $account->getId(),
						'accountName' => $account->getName(),
						// True: listed for the user to check, never switched
						'review' => $tx->getBillId() !== null || (bool)$tx->getReconciled(),
					];
				}
			}
		}

		return $found;
	}

	/**
	 * Fix future-dated cleared transactions by setting them to scheduled
	 * and reversing their balance impact.
	 */
	private function repairFutureClearedTransactions(string $userId): array {
		$found = $this->findFutureClearedTransactions($userId);
		$fixed = 0;

		foreach ($found as $item) {
			if ($item['review']) {
				continue;
			}
			try {
				$tx = $this->transactionMapper->findById($item['transactionId']);
				if (!$tx || $tx->getStatus() === 'scheduled' || $tx->getBillId() !== null || $tx->getReconciled()) {
					continue;
				}

				// Change to scheduled
				$tx->setStatus('scheduled');
				$tx->setUpdatedAt(date('Y-m-d H:i:s'));
				$this->transactionMapper->update($tx);

				$fixed++;
			} catch (\Exception $e) {
				// Skip on error
			}
		}

		// Recompute balances from the ledger (scheduled rows no longer count)
		if ($fixed > 0) {
			$this->accountService->recalculateAllBalances($userId);
		}

		return ['fixed' => $fixed, 'found' => count($found)];
	}

