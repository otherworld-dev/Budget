<?php

declare(strict_types=1);

namespace OCA\Budget\Tests\Unit\Service;

use OCA\Budget\Db\Account;
use OCA\Budget\Db\AccountMapper;
use OCA\Budget\Db\Bill;
use OCA\Budget\Db\BillMapper;
use OCA\Budget\Db\Transaction;
use OCA\Budget\Db\TransactionMapper;
use OCA\Budget\Service\AccountService;
use OCA\Budget\Service\Bill\FrequencyCalculator;
use OCA\Budget\Service\RepairService;
use OCA\Budget\Service\TransactionService;
use OCA\Budget\Service\UserClock;
use PHPUnit\Framework\TestCase;

/**
 * The name Repair Data lists a duplicate payment under (#399).
 *
 * A payment with no vendor goes by its own description. The scan sent the
 * vendor of the payment it repeats in its place, so once that other row
 * had a vendor ('Christian Shop AG', set by hand or by an import), the row
 * read 'Christian Shop AG 91.58 CHF 2026-03-26 Also recorded as Christian
 * Shop AG on 2026-03-28': named twice after the other row, and its own
 * description shown nowhere. The other row is named by the note, through
 * originalDescription.
 */
class RepairServiceDuplicateNameTest extends TestCase {
	private const USER_ID = 'testuser';

	private TransactionMapper $transactionMapper;
	private BillMapper $billMapper;
	private AccountMapper $accountMapper;

	protected function setUp(): void {
		$this->transactionMapper = $this->createMock(TransactionMapper::class);
		$this->billMapper = $this->createMock(BillMapper::class);
		$this->accountMapper = $this->createMock(AccountMapper::class);

		$account = new Account();
		$account->setId(1);
		$account->setName('Lohnkonto');
		$account->setBalance(0.0);
		$account->setOpeningBalance(0.0);
		$account->setUserId(self::USER_ID);
		$account->setType('checking');
		$this->accountMapper->method('findAll')->with(self::USER_ID)->willReturn([$account]);
	}

	private function service(): RepairService {
		$clock = $this->createMock(UserClock::class);
		$clock->method('today')->willReturn('2026-10-15');
		$clock->method('isFutureDate')->willReturnCallback(fn (string $date) => $date > '2026-10-15');
		return new RepairService(
			$this->transactionMapper,
			$this->billMapper,
			$this->accountMapper,
			new FrequencyCalculator(),
			$this->createMock(AccountService::class),
			$this->createMock(TransactionService::class),
			$clock
		);
	}

	private function tx(array $fields): Transaction {
		$fields += [
			'type' => 'debit', 'status' => 'cleared', 'accountId' => 1, 'billId' => null,
			'notes' => null, 'reconciled' => false, 'importId' => null,
		];
		$tx = new Transaction();
		$tx->setId($fields['id']);
		$tx->setAccountId($fields['accountId']);
		$tx->setDate($fields['date']);
		$tx->setAmount($fields['amount']);
		$tx->setType($fields['type']);
		$tx->setStatus($fields['status']);
		$tx->setVendor($fields['vendor']);
		$tx->setDescription($fields['description']);
		$tx->setNotes($fields['notes']);
		$tx->setCreatedAt($fields['createdAt'] ?? $fields['date'] . ' 09:00:00');
		$tx->setUpdatedAt($fields['updatedAt'] ?? $fields['date'] . ' 09:00:00');
		$tx->setBillId($fields['billId']);
		$tx->setReconciled($fields['reconciled']);
		$tx->setImportId($fields['importId']);
		return $tx;
	}

	/**
	 * Back the mapper with these rows, as RepairServiceTest does.
	 *
	 * @param Transaction[] $ledger
	 * @param Bill[] $bills
	 */
	private function withLedger(array $ledger, array $bills = []): void {
		$scheduled = fn (Transaction $t): bool => ($t->getStatus() ?? 'cleared') === 'scheduled';
		$this->billMapper->method('findAll')->with(self::USER_ID)->willReturn($bills);
		$this->transactionMapper->method('findAutoGeneratedBillTransactions')->willReturnCallback(
			fn (int $accountId) => array_values(array_filter($ledger, fn (Transaction $t) => $t->getAccountId() === $accountId
				&& str_starts_with($t->getNotes() ?? '', 'Auto-generated from bill:') && !$scheduled($t)))
		);
		$this->transactionMapper->method('findRowsByDateRange')->willReturnCallback(
			function (int $accountId, string $from, string $to) use ($ledger) {
				$rows = [];
				foreach ($ledger as $t) {
					if ($t->getAccountId() === $accountId && $t->getDate() >= $from && $t->getDate() <= $to) {
						$rows[] = [
							'id' => $t->getId(), 'account_id' => $t->getAccountId(), 'category_id' => null,
							'date' => $t->getDate(), 'amount' => $t->getAmount(), 'type' => $t->getType(),
							'status' => $t->getStatus(), 'vendor' => $t->getVendor(), 'description' => $t->getDescription(),
							'notes' => $t->getNotes(), 'created_at' => $t->getCreatedAt(), 'bill_id' => $t->getBillId(),
							'reconciled' => $t->getReconciled(), 'import_id' => $t->getImportId(),
						];
					}
				}
				usort($rows, fn (array $a, array $b) => [$b['date'], $b['id']] <=> [$a['date'], $a['id']]);
				return $rows;
			}
		);
		$this->transactionMapper->method('findRecordedByBillIds')->willReturnCallback(
			fn (array $billIds) => array_values(array_filter($ledger, fn (Transaction $t) => in_array($t->getBillId(), $billIds, true) && !$scheduled($t)))
		);
		$this->transactionMapper->method('findById')->willReturnCallback(function (int $id) use ($ledger) {
			foreach ($ledger as $t) {
				if ($t->getId() === $id) {
					return $t;
				}
			}
			return null;
		});
	}

	/**
	 * The reporter's March double: the 2.x job's row of the since deleted
	 * bill, with its bill's name in the description and no vendor, and the
	 * row typed in for the same payment, since given a vendor.
	 */
	private function christian(array $generated = [], array $typed = []): array {
		return [
			$this->tx($generated + [
				'id' => 1599732, 'date' => '2026-03-26', 'amount' => 91.58,
				'vendor' => null, 'description' => 'Uhrenschmuck24 Christian (own text of the 26 Mar row)',
				'notes' => 'Auto-generated from bill: Christian Uhrenschmuck24',
			]),
			$this->tx($typed + [
				'id' => 1599850, 'date' => '2026-03-28', 'amount' => 91.59,
				'vendor' => 'Christian Shop AG', 'description' => 'Christian Uhrenschmuck24',
			]),
		];
	}

	private function onlyFinding(): array {
		$found = $this->service()->diagnose(self::USER_ID)['duplicateTransactions'];
		$this->assertCount(1, $found);
		return $found[0];
	}

	public function testAPaymentWithNoVendorIsNotGivenTheOtherRowsVendor(): void {
		$this->withLedger($this->christian());

		$finding = $this->onlyFinding();

		$this->assertSame(1599732, $finding['duplicateId']);
		$this->assertSame(1599850, $finding['originalId']);
		$this->assertNull($finding['vendor'], 'the row has no vendor of its own');
		$this->assertSame('Uhrenschmuck24 Christian (own text of the 26 Mar row)', $finding['description']);
		// The note still names the other row, by its vendor
		$this->assertSame('Christian Shop AG', $finding['originalDescription']);
	}

	public function testAnEmptyVendorIsNoVendor(): void {
		$this->withLedger($this->christian(['vendor' => '']));

		$this->assertNull($this->onlyFinding()['vendor']);
	}

	public function testAPaymentKeepsItsOwnVendor(): void {
		$this->withLedger($this->christian(['vendor' => 'Christian Uhrenschmuck24']));

		$finding = $this->onlyFinding();

		$this->assertSame('Christian Uhrenschmuck24', $finding['vendor']);
		$this->assertSame('Christian Shop AG', $finding['originalDescription']);
	}

	public function testNeitherRowHavingAVendorLeavesTheNameToTheDescription(): void {
		$this->withLedger($this->christian([], ['vendor' => null]));

		$finding = $this->onlyFinding();

		$this->assertNull($finding['vendor']);
		$this->assertSame('Uhrenschmuck24 Christian (own text of the 26 Mar row)', $finding['description']);
		$this->assertSame('Christian Uhrenschmuck24', $finding['originalDescription']);
	}

	public function testTwoPaymentsOfOneOccurrenceAreEachNamedByTheirOwnVendor(): void {
		// A one-time bill paid twice by Mark Paid: the newer payment is
		// offered. Its vendor was cleared and a description typed in, and
		// the older one still carries the bill's name as its vendor.
		$bill = new Bill();
		$bill->setId(13963);
		$bill->setName('CembraPay Temu');
		$bill->setFrequency('one-time');
		$bill->setAmount(151.67);
		$bill->setIsActive(false);
		$bill->setUserId(self::USER_ID);
		$bill->setAccountId(1);
		$bill->setStartDate('2026-09-28');
		$bill->setNextDueDate(null);
		$bill->setLastPaidDate('2026-10-15');
		$bill->setDueDay(28);
		$bill->setDueMonth(9);
		$bill->setIsTransfer(false);
		$this->withLedger([
			$this->tx([
				'id' => 1600677, 'date' => '2026-09-27', 'amount' => 151.67, 'billId' => 13963,
				'vendor' => 'CembraPay Temu', 'description' => '', 'notes' => 'Auto-generated from bill: CembraPay Temu',
			]),
			$this->tx([
				'id' => 1600840, 'date' => '2026-10-15', 'amount' => 151.67, 'billId' => 13963,
				'vendor' => null, 'description' => 'CembraPay Temu Oktober', 'notes' => 'Auto-generated from bill: CembraPay Temu',
			]),
		], [$bill]);

		$finding = $this->onlyFinding();

		$this->assertSame('same_occurrence', $finding['reason']);
		$this->assertSame(1600840, $finding['duplicateId']);
		$this->assertNull($finding['vendor']);
		$this->assertSame('CembraPay Temu Oktober', $finding['description']);
		$this->assertSame('CembraPay Temu', $finding['originalDescription']);
	}
}
